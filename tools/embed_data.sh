#!/usr/bin/env bash
# Rebuilds the embedded data blocks of report.tex from report/data/*.dat,
# so the report stays a single self-contained file that compiles on Overleaf.
#
#   usage: ./tools/embed_data.sh [report.tex] [data_dir]
#
# Run this after ./reproduce_benchmarks.sh, otherwise the plots keep the old numbers.
set -euo pipefail
TEX="${1:-report.tex}"
DIR="${2:-report/data}"
FILES=(csweep phivsmeasured wl-elastic wl-funnel wl-standard)

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT
{
  echo '%%% BEGIN EMBEDDED DATA (generated by tools/embed_data.sh, do not edit by hand)'
  echo '%%% Regenerate with ./tools/embed_data.sh after re-running the benchmarks.'
  for f in "${FILES[@]}"; do
      [ -f "$DIR/$f.dat" ] || { echo "missing $DIR/$f.dat" >&2; exit 1; }
      echo "\\begin{filecontents*}[overwrite]{$f.dat}"
      cat "$DIR/$f.dat"
      echo "\\end{filecontents*}"
  done
  echo '%%% END EMBEDDED DATA'
} > "$TMP"

TEX="$TEX" BLOCK="$TMP" python3 <<'PY'
import os, re
tex, blockfile = os.environ['TEX'], os.environ['BLOCK']
block = open(blockfile).read().rstrip('\n')
s = open(tex).read()
begin = '%%% BEGIN EMBEDDED DATA'
end   = '%%% END EMBEDDED DATA'
pat = re.compile(re.escape(begin) + r'.*?' + re.escape(end), re.S)
if pat.search(s):
    s = pat.sub(lambda _: block, s, count=1)
else:
    s = block + '\n' + s.lstrip('\n')   # filecontents must precede \documentclass
open(tex, 'w').write(s)
print(f"embedded {block.count('begin{filecontents')} data files into {tex}")
PY
